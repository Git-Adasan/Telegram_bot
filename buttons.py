def button_texts(action):
    """Все тексты (в нижнем регистре), которыми можно вызвать действие."""
    texts = set(LABELS.get(action, {}).values()) | LEGACY.get(action, set())
    return {t.lower() for t in texts}


def is_button(action):
    """Фильтр для @dp.message(...): сообщение — это нажатие кнопки `action` (на любом языке)."""
    texts = button_texts(action)
    return lambda m: bool(m.text) and m.text.lower() in texts
